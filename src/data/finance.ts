function hydrateFinance(rows: FinanceMetricDraft[]): FinanceMetric[] {
  return rows.map((r) => ({
    ...r,
    stamp: SAMPLE_IDS.has(r.id) ? "sample" : "cited",
    shownOn: r.unit === "GW" ? "excluded" : "finance",
  }));
}

